"""Bundle manifest data as a classic script so the review works over file://."""
from pathlib import Path
import json
import sys

ART = Path(__file__).resolve().parents[2]


def pack(check=False):
    review = ART / 'reviews' / 'four-role-demo'
    entries = json.loads((review / 'index.json').read_text(encoding='utf-8'))
    data = {
        entry['character']: json.loads((ART / entry['manifest']).read_text(encoding='utf-8'))
        for entry in entries
    }
    content = '// Generated by pack_four_role_preview.py; do not edit manually.\n'
    content += 'window.FOUR_ROLE_PREVIEW_DATA = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
    target = review / 'preview-data.js'
    if check:
        if target.read_text(encoding='utf-8') != content:
            raise SystemExit('Preview data is stale; run pack_four_role_preview.py')
        print('PREVIEW_DATA_CHECK: 4 manifests match')
    else:
        target.write_text(content, encoding='utf-8')
        print('Preview manifest bundle written')


if __name__ == '__main__':
    pack(check='--check' in sys.argv)
