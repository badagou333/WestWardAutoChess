"""Bundle manifest data as a classic script so the review works over file://."""
from pathlib import Path
import json
import sys

ART = Path(__file__).resolve().parents[2]


def pack(check=False):
    review = ART / 'reviews' / 'four-role-demo'
    entries = json.loads((review / 'index.json').read_text(encoding='utf-8'))
    data = {
        entry['character']: json.loads((ART / entry['manifest']).read_text(encoding='utf-8'))
        for entry in entries
    }
    # Adapt older samples only in the preview bundle; source manifests stay intact.
    for role in ['guard_monk', 'foxfire_imp']:
        data[role] = json.loads((ART / 'production' / role / 'demo_v1' / 'manifest.json').read_text(encoding='utf-8'))
    monk = data['guard_monk']
    monk['atlases'] = {'body': monk['atlas']['file'], 'vfx': None}
    monk['standalone_vfx'] = {}
    for action in monk['actions'].values():
        action['body_frames'] = action['frames']
        if 'frame_seconds' in action:
            action['body_frame_seconds'] = action['frame_seconds']
    monk['preview_notice'] = '已清底样板：六帧已从确认版八动作稿重新提取，清理腿间、武器围合区域与轮廓残底，补回旧裁切遗漏的棍头和脚部。挥棍轨迹仍在身体图中；动态对齐与正式战斗待验收。'
    fox = data['foxfire_imp']
    fox['standalone_vfx']['basic_projectile']['aligned_center_trial'] = [190, 154]
    fox['preview_notice'] = '待修复样板：衣尾缝隙残底、受击地线与身体锚点仍待修复；蓄力手部火焰含在身体图中。投射物发射点沿用独立审核页的试验值。'
    content = '// Generated by pack_four_role_preview.py; do not edit manually.\n'
    content += 'window.ROLE_PREVIEW_DATA = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
    target = review / 'preview-data.js'
    if check:
        if target.read_text(encoding='utf-8') != content:
            raise SystemExit('Preview data is stale; run pack_four_role_preview.py')
        print(f'PREVIEW_DATA_CHECK: {len(data)} manifests and preview adapters match')
    else:
        target.write_text(content, encoding='utf-8')
        print('Preview manifest bundle written')


if __name__ == '__main__':
    pack(check='--check' in sys.argv)
